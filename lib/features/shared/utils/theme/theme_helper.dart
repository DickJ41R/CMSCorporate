          fontWeight: FontWeight.w700,
        ),
      );
}

/// Class containing the supported color schemes.
class ColorSchemes {
  static const primaryColorScheme = ColorScheme.light(
    // Primary colors
    primary: Color(0XFF137D67),
    secondaryContainer: Color(0XFF13537d),

    // On colors(text colors)
    onPrimary: Color(0XFF13D232),
    onPrimaryContainer: Color(0X87FFFFFF),
  );
}

/// Class containing custom colors for a primary theme.
class PrimaryColors {
  // Black
  Color get black900 => const Color(0XFF000000);

  // Blue
  Color get green50 => const Color(0XFF1DBF9E);

  // BlueGray
  Color get green300 => const Color(0XFF169379);
  Color get green400 => const Color(0XFF137D67);

  // Gray
  Color get gray400 => const Color(0XFFC4C4C4);

  // Indigo
  Color get indigoA200 => const Color(0XFF5B61F4);

  // LightBlue
  Color get lightGreen600 => const Color(0XFF1AA98B);

  // Pink
  Color get pink300 => const Color(0XFFFB7181);

  // Yellow
  Color get yellow700 => const Color(0XFFFFC732);
}

PrimaryColors get appTheme => ThemeHelper().themeColor();
ThemeData get theme => ThemeHelper().themeData();
